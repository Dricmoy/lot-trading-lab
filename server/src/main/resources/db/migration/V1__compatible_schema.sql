-- Existing Django tables remain authoritative. These definitions bootstrap an empty
-- PostgreSQL database and never replace or rewrite existing application records.
CREATE TABLE IF NOT EXISTS auth_user (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 password VARCHAR(128) NOT NULL, last_login TIMESTAMPTZ,
 is_superuser BOOLEAN NOT NULL DEFAULT FALSE, username VARCHAR(150) NOT NULL UNIQUE,
 first_name VARCHAR(150) NOT NULL DEFAULT '', last_name VARCHAR(150) NOT NULL DEFAULT '',
 email VARCHAR(254) NOT NULL DEFAULT '', is_staff BOOLEAN NOT NULL DEFAULT FALSE,
 is_active BOOLEAN NOT NULL DEFAULT TRUE, date_joined TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS django_session (
 session_key VARCHAR(40) PRIMARY KEY, session_data TEXT NOT NULL, expire_date TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS trading_account (
 id UUID PRIMARY KEY, cash BIGINT NOT NULL CHECK(cash>=0), created_at TIMESTAMPTZ NOT NULL,
 user_id INTEGER UNIQUE REFERENCES auth_user(id) DEFERRABLE INITIALLY DEFERRED,
 watchlist JSONB NOT NULL, cash_anchor BIGINT NOT NULL, history_epoch UUID NOT NULL, revision INTEGER NOT NULL CHECK(revision>=0)
);
CREATE TABLE IF NOT EXISTS trading_position (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, symbol VARCHAR(8) NOT NULL,
 quantity INTEGER NOT NULL CHECK(quantity>=0), cost BIGINT NOT NULL,
 account_id UUID NOT NULL REFERENCES trading_account(id) DEFERRABLE INITIALLY DEFERRED,
 UNIQUE(account_id,symbol)
);
CREATE TABLE IF NOT EXISTS trading_order (
 id UUID PRIMARY KEY, key UUID NOT NULL, fingerprint VARCHAR(64) NOT NULL,
 symbol VARCHAR(8) NOT NULL, side VARCHAR(4) NOT NULL, kind VARCHAR(6) NOT NULL,
 requested INTEGER NOT NULL CHECK(requested>=0), executed INTEGER NOT NULL CHECK(executed>=0),
 total BIGINT NOT NULL, status VARCHAR(12) NOT NULL, result JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL,
 account_id UUID NOT NULL REFERENCES trading_account(id) DEFERRABLE INITIALLY DEFERRED,
 "limit" BIGINT NOT NULL, time_in_force VARCHAR(8) NOT NULL, reason TEXT NOT NULL,
 reflection TEXT NOT NULL, realized BIGINT, UNIQUE(account_id,key)
);
CREATE TABLE IF NOT EXISTS trading_ledgerentry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cash_delta BIGINT NOT NULL, cash_after BIGINT NOT NULL, created_at TIMESTAMPTZ NOT NULL,
 account_id UUID NOT NULL REFERENCES trading_account(id) DEFERRABLE INITIALLY DEFERRED,
 order_id UUID NOT NULL UNIQUE REFERENCES trading_order(id) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE IF NOT EXISTS trading_ordermovement (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cash_delta BIGINT NOT NULL,
 cash_after BIGINT NOT NULL, quantity INTEGER NOT NULL CHECK(quantity>=0), total BIGINT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,
 account_id UUID NOT NULL REFERENCES trading_account(id) DEFERRABLE INITIALLY DEFERRED,
 order_id UUID NOT NULL REFERENCES trading_order(id) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE IF NOT EXISTS trading_portfoliosnapshot (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, epoch UUID NOT NULL,
 bucket TIMESTAMPTZ NOT NULL, cash BIGINT NOT NULL, value BIGINT NOT NULL,
 positions JSONB NOT NULL, prices JSONB NOT NULL,
 account_id UUID NOT NULL REFERENCES trading_account(id) DEFERRABLE INITIALLY DEFERRED,
 UNIQUE(account_id,epoch,bucket)
);
CREATE TABLE IF NOT EXISTS trading_replaysession (
 id UUID PRIMARY KEY, scenario VARCHAR(40) NOT NULL, scenario_version INTEGER NOT NULL CHECK(scenario_version>=0),
 start_key UUID NOT NULL, start_fingerprint VARCHAR(64) NOT NULL, state JSONB NOT NULL,
 shared_token UUID UNIQUE, share_notes BOOLEAN NOT NULL,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 account_id UUID NOT NULL REFERENCES trading_account(id) DEFERRABLE INITIALLY DEFERRED,
 UNIQUE(account_id,start_key)
);
CREATE TABLE IF NOT EXISTS trading_replayevent (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, key UUID NOT NULL,
 fingerprint VARCHAR(64) NOT NULL, action VARCHAR(20) NOT NULL, payload JSONB NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,
 session_id UUID NOT NULL REFERENCES trading_replaysession(id) DEFERRABLE INITIALLY DEFERRED,
 UNIQUE(session_id,key)
);
CREATE TABLE IF NOT EXISTS trading_auththrottle (
 key VARCHAR(64) PRIMARY KEY, attempts INTEGER NOT NULL CHECK(attempts>=0), started_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS lot_java_session (
 token_hash CHAR(64) PRIMARY KEY, user_id INTEGER REFERENCES auth_user(id),
 private_account UUID REFERENCES trading_account(id), auth_hash CHAR(64),
 expires_at TIMESTAMPTZ NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS lot_java_session_expiry ON lot_java_session(expires_at);
CREATE TABLE IF NOT EXISTS lot_java_reset (
 token_hash CHAR(64) PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES auth_user(id),
 auth_hash CHAR(64) NOT NULL, expires_at TIMESTAMPTZ NOT NULL, used_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS lot_java_reset_expiry ON lot_java_reset(expires_at);
